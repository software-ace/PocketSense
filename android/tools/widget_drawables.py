def squares(cells):
    return ' '.join(f'M{x},{y}h1v1h-1z' for x, y in cells)


def cells(rows, chars):
    return [(x, y) for y, r in enumerate(rows) for x, c in enumerate(r) if c in chars]


def vector(name, w, h, paths, width_dp=None, height_dp=None, comment=''):
    """paths: list of (colour, pathData[, extra attrs])."""
    body = '\n'.join(
        f'    <path android:fillColor="{c}" android:pathData="{d}"{extra[0] if extra else ""} />'
        for c, d, *extra in paths if d)
    head = f'<!-- {comment} Generated by android/tools/widget_drawables.py: edit the sprite there. -->\n' if comment else ''
    (OUT / f'{name}.xml').write_text(
        f'<?xml version="1.0" encoding="utf-8"?>\n{head}'
        f'<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{width_dp or w * 3}dp" android:height="{height_dp or h * 3}dp"\n'
        f'    android:viewportWidth="{w}" android:viewportHeight="{h}">\n{body}\n</vector>\n')


def outline(rows):
    on = lambda x, y: 0 <= y < len(rows) and 0 <= x < len(rows[0]) and rows[y][x] == '#'
    return [(x, y) for y in range(len(rows)) for x in range(len(rows[0]))
            if not on(x, y) and (on(x - 1, y) or on(x + 1, y) or on(x, y - 1) or on(x, y + 1))]


