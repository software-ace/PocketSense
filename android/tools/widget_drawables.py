def rounded_rect(w, h, r, inset=0.0):
    x0, y0, x1, y1 = inset, inset, w - inset, h - inset
    r = r - inset
    return (f'M{x0 + r:.2f},{y0:.2f} H{x1 - r:.2f} A{r:.2f},{r:.2f} 0 0 1 {x1:.2f},{y0 + r:.2f} '
            f'V{y1 - r:.2f} A{r:.2f},{r:.2f} 0 0 1 {x1 - r:.2f},{y1:.2f} H{x0 + r:.2f} '
            f'A{r:.2f},{r:.2f} 0 0 1 {x0:.2f},{y1 - r:.2f} V{y0 + r:.2f} A{r:.2f},{r:.2f} 0 0 1 {x0 + r:.2f},{y0:.2f} Z')


def stitches(w, h, r, inset, dash=4.0, gap=3.0, thick=1.4):
    """Short strokes along a rounded rectangle, as filled quads (vectors have no dash)."""
    x0, y0, x1, y1, rr = inset, inset, w - inset, h - inset, r - inset
    segs = [('l', (x0 + rr, y0), (x1 - rr, y0)), ('a', (x1 - rr, y0 + rr), -90),
            ('l', (x1, y0 + rr), (x1, y1 - rr)), ('a', (x1 - rr, y1 - rr), 0),
            ('l', (x1 - rr, y1), (x0 + rr, y1)), ('a', (x0 + rr, y1 - rr), 90),
            ('l', (x0, y1 - rr), (x0, y0 + rr)), ('a', (x0 + rr, y0 + rr), 180)]

    def point(s, t):
        if s[0] == 'l':
            (ax, ay), (bx, by) = s[1], s[2]
            return ax + (bx - ax) * t, ay + (by - ay) * t
        (cx, cy), start = s[1], s[2]
        a = math.radians(start + 90 * t)
        return cx + rr * math.cos(a), cy + rr * math.sin(a)

    lengths = [math.dist(s[1], s[2]) if s[0] == 'l' else math.pi * rr / 2 for s in segs]
    total = sum(lengths)

    def at(d):
        d %= total
        for s, ln in zip(segs, lengths):
            if d <= ln:
                return point(s, d / ln)
            d -= ln
        return point(segs[-1], 1)

    out, d = [], 0.0
    while d + dash <= total:
        (ax, ay), (bx, by) = at(d), at(d + dash)
        nx, ny = -(by - ay), bx - ax
        n = math.hypot(nx, ny) or 1
        nx, ny = nx / n * thick / 2, ny / n * thick / 2
        out.append(f'M{ax + nx:.2f},{ay + ny:.2f} L{bx + nx:.2f},{by + ny:.2f} L{bx - nx:.2f},{by - ny:.2f} L{ax - nx:.2f},{ay - ny:.2f} Z')
        d += dash + gap
    return ' '.join(out)


def grain(w, h, n, seed):
    rnd = random.Random(seed)
    return ' '.join(f'M{rnd.uniform(2, w - 3):.1f},{rnd.uniform(2, h - 3):.1f}h0.7v0.7h-0.7z' for _ in range(n))


