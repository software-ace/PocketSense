# Quick add in each style (Plain keeps quick_add_widget.xml). Labels are a
# TextView for the picker's preview, swapped for a pixel-font bitmap by
# QuickAddWidget.kt once it draws.
def qa_button(id_, kind, bg, icon, label_colour, icon_bg=None, end=5):
    icon_view = (f'<ImageView android:layout_width="15dp" android:layout_height="21dp" android:importantForAccessibility="no" '
                 f'android:scaleType="fitXY" android:src="@drawable/{icon}" />')
    if icon_bg:  # a round console button with the arrow on it
        icon_view = (f'<FrameLayout android:layout_width="34dp" android:layout_height="34dp" android:background="@drawable/{icon_bg}">\n'
                     f'                <ImageView android:layout_width="12dp" android:layout_height="17dp" android:layout_gravity="center" '
                     f'android:importantForAccessibility="no" android:scaleType="fitXY" android:src="@drawable/{icon}" />\n            </FrameLayout>')
    bg_attr = f' android:background="@drawable/{bg}"' if bg else ''
    return (f'<LinearLayout android:id="@+id/{id_}" android:layout_width="0dp" android:layout_height="match_parent" '
            f'android:layout_weight="1" android:layout_marginEnd="{end}dp"{bg_attr} android:gravity="center" android:orientation="vertical">\n'
            f'            {icon_view}\n'
            f'            <TextView android:id="@+id/qa_{kind}_text" android:layout_width="wrap_content" android:layout_height="wrap_content" '
            f'android:layout_marginTop="3dp" android:maxLines="1" android:text="@string/quick_add_{kind}" android:textColor="{label_colour}" '
            f'android:textSize="11sp" android:textStyle="bold" />\n'
            f'            <ImageView android:id="@+id/qa_{kind}_label" android:layout_width="wrap_content" android:layout_height="14dp" '
            f'android:layout_marginTop="4dp" android:adjustViewBounds="true" android:scaleType="centerInside" android:visibility="gone" />\n'
            f'        </LinearLayout>')


def quick_add(style, comment, bg, exp_bg, inc_bg, voice_bg, exp_colour, inc_colour, round_bg=None, voice_pill=False):
    voice_icon = (f'<ImageView android:layout_width="18dp" android:layout_height="23dp" '
                  f'android:importantForAccessibility="no" android:scaleType="fitCenter" android:src="@drawable/widget_qa_voice_{style}" />')
    if voice_pill:  # a third round console button, grey, as legible as the other two
        voice_icon = (f'<FrameLayout android:layout_width="34dp" android:layout_height="34dp" android:background="@drawable/widget_qa_btn_lcd_voice">\n'
                      f'                <ImageView android:layout_width="13dp" android:layout_height="17dp" android:layout_gravity="center" '
                      f'android:importantForAccessibility="no" android:scaleType="fitXY" android:src="@drawable/widget_qa_voice_{style}" />\n            </FrameLayout>')
    voice_bg_attr = f' android:background="@drawable/{voice_bg}"' if voice_bg else ''
    if voice_pill:  # in line with the other round buttons, which have a label under them
        voice_bg_attr += ' android:paddingBottom="19dp"'
    (OUT / f'quick_add_{style}.xml').write_text(
        f'<?xml version="1.0" encoding="utf-8"?>\n<!-- Quick add, {comment} Generated by android/tools/widget_layouts.py. -->\n'
        f'<FrameLayout {NS}\n    android:id="@android:id/background"\n    android:layout_width="match_parent"\n'
        f'    android:layout_height="match_parent"\n    android:background="@drawable/{bg}">\n'
        f'    <LinearLayout android:layout_width="match_parent" android:layout_height="match_parent" android:orientation="horizontal" android:padding="9dp">\n'
        f'        {qa_button("quick_add_expense", "expense", exp_bg, f"widget_qa_expense_{style}", exp_colour, round_bg)}\n'
        f'        {qa_button("quick_add_income", "income", inc_bg, f"widget_qa_income_{style}", inc_colour, round_bg)}\n'
        f'        <LinearLayout android:id="@+id/quick_add_voice" android:layout_width="44dp" android:layout_height="match_parent"{voice_bg_attr} '
        f'android:gravity="center" android:contentDescription="@string/quick_add_voice">\n            {voice_icon}\n        </LinearLayout>\n'
        f'    </LinearLayout>\n</FrameLayout>\n')


