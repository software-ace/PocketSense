"""Usage: python3 android/tools/widget_layouts.py android/app/src/main/res/layout

Writes the 8 widget-style layouts. Every layout has every slot id (unused
ones stay gone), so BalanceWidgets.kt can fill any style the same way."""
import sys
from pathlib import Path

OUT = Path(sys.argv[1])
NS = 'xmlns:android="http://schemas.android.com/apk/res/android"'


def margins(m):
    names = {'t': 'layout_marginTop', 'b': 'layout_marginBottom', 's': 'layout_marginStart', 'e': 'layout_marginEnd'}
    return ' '.join(f'android:{names[k]}="{v}dp"' for k, v in m.items())


def deco(src, w, h, grav, **m):
    size = (f'android:layout_width="{w}dp"' if w != 'match' else 'android:layout_width="match_parent"')
    return (f'<ImageView {size} android:layout_height="{h}dp" android:layout_gravity="{grav}" {margins(m)} '
            f'android:scaleType="fitXY" android:importantForAccessibility="no" android:src="@drawable/{src}" />')


def line(colour, grav, h, **m):
    return f'<FrameLayout android:layout_width="match_parent" android:layout_height="{h}dp" android:layout_gravity="{grav}" {margins(m)} android:background="{colour}" />'


def slot(id_, h, grav='start', **m):
    height = 'wrap_content' if h == 'wrap' else f'{h}dp'
    return (f'<ImageView android:id="@+id/{id_}" android:layout_width="wrap_content" android:layout_height="{height}" '
            f'android:layout_gravity="{grav}" {margins(m)} android:adjustViewBounds="true" android:scaleType="centerInside" '
            f'android:visibility="gone" />')


def group(id_, items, gone=False):
    vis = ' android:visibility="gone"' if gone else ''
    inner = '\n        '.join(items)
    return (f'<FrameLayout android:id="@+id/{id_}" android:layout_width="match_parent" android:layout_height="match_parent"{vis}>\n'
            f'        {inner}\n    </FrameLayout>')


def column(slots, pad, center=False):
    p = ' '.join(f'android:padding{k}="{v}dp"' for k, v in pad.items())
    grav = ' android:gravity="center_vertical"' if center else ''
    inner = '\n        '.join(slots)
    return (f'<LinearLayout android:layout_width="match_parent" android:layout_height="match_parent" '
            f'android:orientation="vertical" {p}{grav}>\n        {inner}\n    </LinearLayout>')


def layout(name, comment, bg, awake, asleep, extras, col, top=(), brand=None, stamp=None):
    brand = brand or slot('widget_brand', 8, 'top|start')
    stamp = stamp or slot('widget_stamp', 'wrap', 'center')
    body = '\n    '.join([*top, group('widget_awake', awake), group('widget_asleep', asleep, gone=True), *extras, brand, col, stamp])
    (OUT / f'{name}.xml').write_text(
        f'<?xml version="1.0" encoding="utf-8"?>\n<!-- {comment} The text is drawn into the slots by\n'
        f'     BalanceWidgets.kt: widgets can\'t use an app\'s fonts. Generated by android/tools/widget_layouts.py. -->\n'
        f'<FrameLayout {NS}\n    android:id="@android:id/background"\n    android:layout_width="match_parent"\n'
        f'    android:layout_height="match_parent"\n    android:background="@drawable/{bg}">\n    {body}\n</FrameLayout>\n')


def overview_slots(label, amount, label2, amount2, amount_grav='start', gap=8, amount_top=2):
    return [slot('widget_label', label), slot('widget_amount', amount, amount_grav, t=amount_top),
            slot('widget_label2', label2, t=gap), slot('widget_amount2', amount2, amount_grav, t=2),
            slot('widget_hint', 'wrap', t=6)]


# label_end keeps a long account name clear of the cat in the top corner.
def account_slots(label, amount, amount_grav='start', label_end=0):
    return [slot('widget_label', label, e=label_end), slot('widget_amount', amount, amount_grav, t=4),
            slot('widget_label2', 12), slot('widget_amount2', 12), slot('widget_hint', 'wrap')]


