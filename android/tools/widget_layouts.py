# 5 · Plain: the first design. Real TextViews in the system font, so the
# colours follow light and dark mode live; Kotlin sets text instead of bitmaps.
def text(id_, size, colour, h='wrap', bold=False, auto=None, lines=1, **m):
    height = 'wrap_content' if h == 'wrap' else f'{h}dp'
    fit = (f' android:autoSizeTextType="uniform" android:autoSizeMinTextSize="{auto[0]}sp" android:autoSizeMaxTextSize="{auto[1]}sp"'
           if auto else '')
    return (f'<TextView android:id="@+id/{id_}" android:layout_width="match_parent" android:layout_height="{height}" {margins(m)} '
            f'android:maxLines="{lines}" android:ellipsize="end" android:textAlignment="viewStart" '
            f'android:textColor="@color/{colour}" android:textSize="{size}sp"{fit}'
            f'{" android:textStyle=&quot;bold&quot;" if bold else ""} android:visibility="gone" />').replace('&quot;', '"')


